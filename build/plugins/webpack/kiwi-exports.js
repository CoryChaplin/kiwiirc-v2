const fs = require('fs');
const path = require('path');
const NormalModule = require('webpack').NormalModule;

const utils = require('../../utils');

// A top level 'kiwi public' directive marks a module as part of the plugin API
const directiveRegex = /^\s*(?:void\s+)?['"]kiwi public['"];?\s*$/m;
const fileRegex = /\.(vue|js)$/;

/**
 * Webpack plugin providing the `kiwi:exports` virtual module.
 *
 * Instead of every 'kiwi public' module exposing itself through CommonJS `exports` (which
 * requires the whole app to be transpiled to CommonJS), this generates a single ES module
 * that imports each of them as a namespace and exports a registry of them:
 *
 *     import * as m0 from '@/components/UserBox.vue';
 *     export default { 'components/UserBox': m0, ... };
 *
 * GlobalApi uses that registry for kiwi.require() and kiwi.replaceModule().
 */
module.exports = class KiwiExportsPlugin {
    constructor(options = {}) {
        this.sourceDir = options.sourceDir || utils.pathResolve('src');
        this.scheme = options.scheme || 'kiwi';
        // Directories (relative to sourceDir) that are not part of the app itself. src/thirdparty
        // holds optional site customisations that are only built when imported from main.js
        this.exclude = options.exclude || ['thirdparty'];
    }

    apply(compiler) {
        const pluginName = this.constructor.name;

        compiler.hooks.compilation.tap(pluginName, (compilation, { normalModuleFactory }) => {
            normalModuleFactory.hooks.resolveForScheme
                .for(this.scheme)
                .tap(pluginName, (resourceData) => {
                    const url = resourceData.resource;
                    resourceData.path = url;
                    resourceData.resource = url + '.js';
                    return true;
                });

            NormalModule.getCompilationHooks(compilation).readResource
                .for(this.scheme)
                .tapAsync(pluginName, (loaderContext, callback) => {
                    const name = loaderContext.resourcePath.split(':')[1];
                    if (name !== 'exports.js') {
                        callback(new Error(`Unknown ${this.scheme}: module "${name}"`));
                        return;
                    }

                    try {
                        const excluded = this.exclude.map((dir) => path.join(this.sourceDir, dir) + path.sep);
                        const files = getFiles(this.sourceDir)
                            .filter((file) => !excluded.some((dir) => file.startsWith(dir)));
                        // Rebuild when a file is added, removed or gains/loses the directive
                        loaderContext.addContextDependency(this.sourceDir);
                        files.forEach((file) => loaderContext.addDependency(file));

                        const publicFiles = files.filter(
                            (file) => directiveRegex.test(fs.readFileSync(file, 'utf8'))
                        );
                        callback(null, this.generate(publicFiles));
                    } catch (err) {
                        callback(err);
                    }
                });
        });
    }

    generate(publicFiles) {
        const imports = [];
        const entries = [];

        publicFiles.sort().forEach((file, idx) => {
            const relative = path.relative(this.sourceDir, file).split(path.sep).join('/');
            const key = relative.replace(fileRegex, '');
            imports.push(`import * as m${idx} from ${JSON.stringify('@/' + relative)};`);
            entries.push(`    ${JSON.stringify(key)}: m${idx},`);
        });

        return [
            '// Generated by build/plugins/webpack/kiwi-exports.js',
            ...imports,
            '',
            'export default {',
            ...entries,
            '};',
            '',
        ].join('\n');
    }
};

function getFiles(dir) {
    const files = [];
    fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
        const entryPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...getFiles(entryPath));
        } else if (fileRegex.test(entry.name)) {
            files.push(entryPath);
        }
    });
    return files;
}
